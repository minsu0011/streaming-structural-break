"""Explicit-file handoff archives with byte manifests and guarded fresh extraction."""
from pathlib import Path, PurePosixPath
import hashlib
import json
import os
import stat
import zipfile

MANIFEST = 'PACKAGE_MANIFEST_NEXT7.json'
FORBIDDEN_PARTS = frozenset(('data', 'credentials', '__pycache__', '.git', '.venv', '.figure-venv',
    'numba_cache', 'browser_profile', 'reproduction', 'rp_cache', 'cache'))
FORBIDDEN_SUFFIXES = frozenset(('.zip', '.7z', '.tar', '.gz', '.parquet', '.feather', '.pkl', '.npy',
    '.pem', '.key', '.pyc', '.pyo', '.sqlite', '.db', '.log'))
FORBIDDEN_FILES = frozenset(('event_timing_forensic_g1.csv', 'event_timing_forensic_g2.csv',
    'h_calibration_rp_g1.csv', 'h_calibration_rp_g2.csv'))
SAFE_NUMPY_FILES = frozenset(('artifacts/next7/synthetic_stats/COUNTS_2000x512.npy', *(
    f'artifacts/next7/bootstrap/{generation}/{method}/fold_{fold}.npy'
    for generation, methods in (
        ('g1',('M0','I4_EVENT_SCALE_TREE','I3_CURRENT_EVENT','M_FULL','M_EVENT','M_CURRENT')),
        ('g2',('G2_EVENT','G2_FULL')),('g3',('G3_PAIRWISE_FULL',)))
    for method in methods for fold in range(5))))
WINDOWS_DEVICES = frozenset(('CON','PRN','AUX','NUL',*(f'COM{i}' for i in range(1,10)),*(f'LPT{i}' for i in range(1,10))))
SAFE_DATA_SOURCE_FILES = frozenset('src/data/'+name for name in
    ('audit.py','grouping.py','labels.py','loader.py','__init__.py'))


def checked_name(name):
    if not isinstance(name, str) or not name or '\\' in name or ':' in name or '\x00' in name:
        raise ValueError('A normalized relative POSIX file name is required')
    p = PurePosixPath(name)
    if p.is_absolute() or str(p) != name or any(part in ('.','..') for part in p.parts):
        raise ValueError('Archive traversal or non-normalized name')
    for part in p.parts:
        if part.endswith((' ', '.')) or part.split('.')[0].upper() in WINDOWS_DEVICES:
            raise ValueError('Unsafe Windows file name')
        reviewed_source_directory = part=='data' and name in SAFE_DATA_SOURCE_FILES
        if (part.lower() in FORBIDDEN_PARTS and not reviewed_source_directory) or part.lower().startswith('.env'):
            raise ValueError('Excluded data, cache or credential directory')
    if p.name.lower() in FORBIDDEN_FILES or (p.suffix.lower() in FORBIDDEN_SUFFIXES and name not in SAFE_NUMPY_FILES):
        raise ValueError('Excluded data, individual RP evidence or nested archive')
    return name


def sha256(path):
    value = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for block in iter(lambda: handle.read(1 << 20), b''):
            value.update(block)
    return value.hexdigest()


def checked_source(root, relative):
    checked_name(relative)
    root = Path(root).resolve(strict=True)
    path = root / relative
    if not path.resolve(strict=True).is_relative_to(root):
        raise ValueError('Export source escapes the project')
    for component in (path, *path.parents):
        if component == root:
            break
        if component.is_symlink() or (hasattr(component, 'is_junction') and component.is_junction()):
            raise ValueError('Linked export sources are not permitted')
    if not path.is_file():
        raise ValueError('An explicit regular file is required')
    return path


def create_archive(root, files, destination, metadata):
    """Create only; a file's digest and byte count are checked during streaming."""
    root, destination = Path(root).resolve(strict=True), Path(destination)
    names = sorted(checked_name(str(name)) for name in files)
    if not names or len(names) != len(set(name.casefold() for name in names)):
        raise ValueError('A nonempty unique Windows-safe allowlist is required')
    if MANIFEST.casefold() in {name.casefold() for name in names}:
        raise ValueError('The internal byte manifest is generated by the exporter')
    inventory = {}
    for name in names:
        path = checked_source(root, name)
        inventory[name] = {'sha256':sha256(path),'bytes':path.stat().st_size}
    manifest = {'format':'NEXT7_EXPLICIT_BYTE_MANIFEST_V1','metadata':metadata,
        'files':inventory,'self_hash_excluded':True,'raw_competition_data_included':False}
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, 'x', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for name in names:
            path = checked_source(root, name)
            size, value = 0, hashlib.sha256()
            info = zipfile.ZipInfo(name, date_time=(2026,9,13,0,0,0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (stat.S_IFREG | 0o644) << 16
            with path.open('rb') as source, archive.open(info, 'w', force_zip64=True) as target:
                for block in iter(lambda:source.read(1 << 20),b''):
                    target.write(block)
                    size += len(block)
                    value.update(block)
            if size != inventory[name]['bytes'] or value.hexdigest() != inventory[name]['sha256']:
                raise RuntimeError('Export input changed while being archived: ' + name)
        archive.writestr(MANIFEST, json.dumps(manifest,ensure_ascii=False,indent=2,allow_nan=False)+'\n')
    return manifest


def extract_verified(archive_path, destination, *, max_total_bytes=1_000_000_000, max_entry_bytes=200_000_000):
    """Validate the complete central directory and bytes before writing any file."""
    destination = Path(destination)
    if destination.exists():
        raise FileExistsError('Reproduction extraction requires a fresh directory')
    with zipfile.ZipFile(archive_path) as archive:
        infos = archive.infolist()
        names = [checked_name(info.filename) for info in infos]
        if len(names) != len(set(name.casefold() for name in names)) or names.count(MANIFEST) != 1:
            raise ValueError('Duplicate file names or missing unique manifest')
        if sum(info.file_size for info in infos) > max_total_bytes:
            raise ValueError('Archive exceeds the declared handoff byte budget')
        for info in infos:
            if info.is_dir() or stat.S_ISLNK(info.external_attr >> 16) or info.file_size > max_entry_bytes:
                raise ValueError('Only bounded regular file entries are allowed')
        manifest = json.loads(archive.read(MANIFEST))
        if manifest.get('format') != 'NEXT7_EXPLICIT_BYTE_MANIFEST_V1':
            raise ValueError('Unknown handoff byte-manifest format')
        inventory = manifest['files']
        if set(inventory) != set(names) - {MANIFEST}:
            raise ValueError('Manifest and archive members differ')
        for info in infos:
            if info.filename == MANIFEST:
                continue
            expected = inventory[info.filename]
            size, value = 0, hashlib.sha256()
            with archive.open(info) as handle:
                for block in iter(lambda:handle.read(1 << 20),b''):
                    size += len(block)
                    value.update(block)
            if size != expected['bytes'] or value.hexdigest() != expected['sha256']:
                raise ValueError('Archive byte hash mismatch: ' + info.filename)
        destination.mkdir(parents=True,exist_ok=False)
        resolved = destination.resolve(strict=True)
        for info in infos:
            path = destination / info.filename
            if not path.resolve().is_relative_to(resolved):
                raise ValueError('Extraction would leave its fresh target directory')
            path.parent.mkdir(parents=True,exist_ok=True)
            with archive.open(info) as source, path.open('xb') as target:
                for block in iter(lambda:source.read(1 << 20),b''):
                    target.write(block)
        return manifest
